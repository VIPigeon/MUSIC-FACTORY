function qr.draw()
    local scale = 1      -- размер одного модуля QR в пикселях
    local ox = 200        -- смещение по X
    local oy = 100        -- смещение по Y

    local BLACK = 0
    local WHITE = 4

    for y = 1, #qr.code do
        local row = qr.code[y]
        for x = 1, #row do
            local color = WHITE
            if row:sub(x, x) == "1" then
                color = BLACK
            end

            for dy = 0, scale - 1 do
                for dx = 0, scale - 1 do
                    pix(
                        ox + (x - 1) * scale + dx,
                        oy + (y - 1) * scale + dy,
                        color
                    )
                end
            end
        end
    end
end